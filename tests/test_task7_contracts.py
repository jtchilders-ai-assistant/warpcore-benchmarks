class TestG3SchemaFailClosed(unittest.TestCase):
    """Schema validation must fail-closed, not silently skip, when the schema
    file or contract helper is unavailable.

    Current behavior: _validate_manifest_schema / _validate_status_schema both
    do `except ImportError: pass` and `if not schema.exists(): return` — silently skipping.

    The task requires: if schema validation cannot be performed due to missing
    schema files or unavailable helper, treat it as a validation error (fail-closed).
    """

    def test_validate_with_existing_schema_does_not_silently_pass_bad_manifest(self):
        """When schema files exist, a manifest with schema_version=99 must be rejected.

        This test also verifies schema validation is not a no-op regardless of implementation path.
        """
        schema_dir = _REPO_ROOT / "suite" / "schemas"
        if not schema_dir.exists():
            self.skipTest("Schema directory not present; G3 will be tested via other means")

        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            # Corrupt schema_version to an invalid value
            manifest = json.loads((run_dir / "manifest.json").read_text())
            manifest["schema_version"] = 99  # must not be 1
            (run_dir / "manifest.json").write_text(json.dumps(manifest))

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)
            # If the schema validator works AND is not silently skipped, this must fail
            # If contract is importable and schema exists, we MUST reject schema_version=99
            try:
                from contract import validate_json  # noqa: F401
                schema_present = schema_dir.exists()
                if schema_present:
                    self.assertFalse(
                        result.passed,
                        f"validate() must reject manifest with schema_version=99 "
                        f"when schema and contract helper are both available. "
                        f"errors: {result.errors}"
                    )
            except ImportError:
                # contract not importable: test that at minimum we don't pass blindly
                # (fall through — other gates should catch it or skip test)
                self.skipTest("contract module not importable; G3 covered by integration")

    def test_schema_validation_catches_nonfinite_scores(self):
        """Aggregate score file with NaN must be detected by reconciliation, not silently passed.

        This is partly G8 (non-finite scores) but also validates that the validator
        does not silently skip checks when data is malformed.
        """
        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            # Write an aggregate result with "NaN" string (non-parseable as float after json decode)
            agg_path = run_dir / "raw" / "results_test.json"
            # JSON doesn't support NaN directly, but the score string might be empty/null
            agg_path.write_text(json.dumps({
                "results": {"gsm8k": {"exact_match,flexible-fallback": None}},
                "n_samples": 5,
            }))

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml,
                                               for_publication=True)
            # A None score cannot be reconciled; for_publication=True requires aggregate presence
            # The validator must not silently skip and return passed=True
            agg_errors = [e for e in result.errors if "aggregate" in e.lower() or
                          "score" in e.lower() or "reconcil" in e.lower()]
            # With score=None in the result, the per-item reconciliation can't match.
            # The test is: does validation NOT silently pass a None aggregate score?
            # If passed=True with a None score, that's the gap.
            if result.passed:
                self.fail(
                    f"validate(for_publication=True) must not pass when aggregate score is null/None. "
                    f"errors: {result.errors}"
                )



_SUITE_CONTENT = "suite_id: warpcore-v1\nsuite_schema_version: 1\n"
_ADAPTER_CONTENT = "adapter_schema_version: 1\ncampaign_status: canonical\n"


def _make_suite_yaml(repo: pathlib.Path, content: str = _SUITE_CONTENT) -> pathlib.Path:
    p = repo / "suite" / "warpcore-v1.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content)
    return p


def _make_adapter_yaml(repo: pathlib.Path, slug: str = "test-model") -> pathlib.Path:
    p = repo / "adapters" / f"{slug}.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(_ADAPTER_CONTENT)
    return p


def _build_quality_run(
    repo: pathlib.Path,
    *,
    model_slug: str = "test-model",
    benchmark: str = "gsm8k",
    n_items: int = 5,
    execution_state: str = "completed",
    lifecycle: str = "current",
    extra_manifest: dict | None = None,
) -> pathlib.Path:
    """Build a minimal quality run (gsm8k-style with samples+per_item)."""
    suite_yaml = _make_suite_yaml(repo)
    suite_hash = hashlib.sha256(suite_yaml.read_bytes()).hexdigest()
    adapter_yaml = _make_adapter_yaml(repo, model_slug)
    adapter_hash = hashlib.sha256(adapter_yaml.read_bytes()).hexdigest()

    run_id = "run-2026-09-15T12-00-00"
    run_dir = repo / "results" / model_slug / "runs" / "warpcore-v1" / benchmark / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    ids = [f"item-{i}" for i in range(n_items)]
    n_correct = n_items  # all correct → score 1.0
    item_rows = [
        {"item_id": iid, "score": 1.0, "disposition": "correct",
         "finish_reason": "stop", "response_chars": 100, "empty_content": False}
        for iid in ids
    ]

    manifest = {
        "schema_version": 1,
        "suite_id": "warpcore-v1",
        "suite_schema_version": 1,
        "run_id": run_id,
        "benchmark": benchmark,
        "adapter_hash": adapter_hash,
        "suite_input_hashes": {"suite/warpcore-v1.yaml": suite_hash},
        "serving_profile_digest": "sha256:" + "c" * 64,
        "model": {"slug": model_slug, "id": f"org/{model_slug}", "revision": "a" * 40},
        "serving": {
            "image_digest": "sha256:" + "d" * 64,
            "engine": "vllm",
            "engine_version": "0.6.6",
            "effective_args": [],
            "environment": {},
            "hardware_id": "dgx-spark-gb10",
        },
        "item_inventory": {
            "expected": n_items,
            "submitted": n_items,
            "instance_ids_hash": hashlib.sha256(
                json.dumps(sorted(ids), sort_keys=True).encode()
            ).hexdigest(),
        },
        "timing": {
            "started_utc": "2026-09-15T12:00:00Z",
            "completed_utc": "2026-09-15T14:00:00Z",
        },
        "artifact_inventory": {
            "samples_jsonl_gz": True,
            "per_item_csv": True,
            "run_log": True,
            "command_txt": True,
            "done_sentinel": True,
        },
    }
    if extra_manifest:
        manifest.update(extra_manifest)

    chain = ["planned", "preflight_passed", "running", "completed", "validated"]
    idx = chain.index(execution_state) if execution_state in chain else 3
    history = [{"state": s, "timestamp": f"2026-09-15T{12+i:02d}:00:00Z"}
               for i, s in enumerate(chain[:idx + 1])]

    status = {
        "schema_version": 1,
        "run_id": run_id,
        "suite_id": "warpcore-v1",
        "execution_state": execution_state,
        "lifecycle": lifecycle,
        "history": history,
    }

    (run_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (run_dir / "status.json").write_text(json.dumps(status, indent=2))
    (run_dir / "DONE").write_text("done\n")
    (run_dir / "run.log").write_text("harness exit 0\n")
    (run_dir / "command.txt").write_text("python3 run_quality.py\n")

    raw_dir = run_dir / "raw"
    raw_dir.mkdir(exist_ok=True)

    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(item_rows[0].keys()))
    w.writeheader()
    w.writerows(item_rows)
    (run_dir / "per_item.csv").write_text(buf.getvalue())

    with gzip.open(raw_dir / f"samples_{benchmark}.jsonl.gz", "wt") as f:
        for row in item_rows:
            f.write(json.dumps(row) + "\n")

    (raw_dir / "results_test.json").write_text(json.dumps({
        "results": {benchmark: {"exact_match,flexible-fallback": 1.0}},
        "n_samples": n_items,
    }))
    return run_dir


def _build_swebench_run(
    repo: pathlib.Path,
    *,
    model_slug: str = "sweb-model",
    n_instances: int = 5,
    execution_state: str = "completed",
    lifecycle: str = "current",
    include_grading: bool = True,
    extra_manifest: dict | None = None,
) -> pathlib.Path:
    """Build a minimal SWE-bench run (preds+exit_statuses+grading_results, no samples/per_item)."""
    suite_yaml = _make_suite_yaml(repo)
    suite_hash = hashlib.sha256(suite_yaml.read_bytes()).hexdigest()
    adapter_yaml = _make_adapter_yaml(repo, model_slug)
    adapter_hash = hashlib.sha256(adapter_yaml.read_bytes()).hexdigest()

    run_id = "run-2026-09-15T12-00-00"
    run_dir = repo / "results" / model_slug / "runs" / "warpcore-v1" / "swebench" / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    instance_ids = [f"repo__repo-{i}" for i in range(n_instances)]

    manifest = {
        "schema_version": 1,
        "suite_id": "warpcore-v1",
        "suite_schema_version": 1,
        "run_id": run_id,
        "benchmark": "swebench",
        "adapter_hash": adapter_hash,
        "suite_input_hashes": {"suite/warpcore-v1.yaml": suite_hash},
        "serving_profile_digest": "sha256:" + "c" * 64,
        "model": {"slug": model_slug, "id": f"org/{model_slug}", "revision": "a" * 40},
        "serving": {
            "image_digest": "sha256:" + "d" * 64,
            "engine": "vllm",
            "engine_version": "0.6.6",
            "effective_args": [],
            "environment": {},
            "hardware_id": "dgx-spark-gb10",
        },
        "item_inventory": {
            "expected": n_instances,
            "submitted": n_instances,
            "instance_ids_hash": hashlib.sha256(
                json.dumps(sorted(instance_ids), sort_keys=True).encode()
            ).hexdigest(),
        },
        "timing": {
            "started_utc": "2026-09-15T12:00:00Z",
            "completed_utc": "2026-09-15T14:00:00Z",
        },
        "artifact_inventory": {
            "preds_json": True,
            "exit_statuses_json": True,
            "grading_results_json": True,
            "run_log": True,
            "command_txt": True,
            "done_sentinel": True,
            # SWE-bench does NOT produce samples_jsonl_gz or per_item_csv
            "samples_jsonl_gz": False,
            "per_item_csv": False,
        },
    }
    if extra_manifest:
        manifest.update(extra_manifest)

    chain = ["planned", "preflight_passed", "running", "completed", "validated"]
    idx = chain.index(execution_state) if execution_state in chain else 3
    history = [{"state": s, "timestamp": f"2026-09-15T{12+i:02d}:00:00Z"}
               for i, s in enumerate(chain[:idx + 1])]
    status = {
        "schema_version": 1,
        "run_id": run_id,
        "suite_id": "warpcore-v1",
        "execution_state": execution_state,
        "lifecycle": lifecycle,
        "history": history,
    }

    (run_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (run_dir / "status.json").write_text(json.dumps(status, indent=2))
    (run_dir / "DONE").write_text("done\n")
    (run_dir / "command.txt").write_text("python3 run_swebench.py\n")

    raw_dir = run_dir / "raw"
    raw_dir.mkdir(exist_ok=True)
    (raw_dir / "run.log").write_text("swebench harness exit 0\n")

    # SWE-bench primary evidence: preds.json, exit_statuses.json, grading_results.json
    preds = {iid: {"model_patch": f"patch_{iid}", "model_name_or_path": model_slug}
             for iid in instance_ids}
    (raw_dir / "preds.json").write_text(json.dumps(preds, indent=2))

    exit_statuses = {iid: "submitted" for iid in instance_ids}
    (raw_dir / "exit_statuses.json").write_text(json.dumps(exit_statuses, indent=2))

    if include_grading:
        grading = {
            "resolved_ids": instance_ids[:2],
            "unresolved_ids": instance_ids[2:4],
            "empty_patch_ids": [],
            "error_ids": [],
            "incomplete_ids": instance_ids[4:],
        }
        (raw_dir / "grading_results.json").write_text(json.dumps(grading, indent=2))

    # SWE-bench post-normalization artifact: trajectories/ directory.
    # Runner normalization copies <id>/<id>.traj.json -> trajectories/<id>.traj for all
    # instances that ran (non-infra-failure). All fixture instances have "submitted" status.
    traj_dir = raw_dir / "trajectories"
    traj_dir.mkdir(exist_ok=True)
    for iid in instance_ids:
        (traj_dir / f"{iid}.traj").write_text(json.dumps({"instance_id": iid, "steps": []}))

    return run_dir



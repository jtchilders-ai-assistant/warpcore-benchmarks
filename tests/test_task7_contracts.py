class TestG8NonFiniteScores(unittest.TestCase):
    """Aggregate reconciliation must fail when per-item scores are missing or non-finite.

    Current implementation: _check_aggregate_reconciliation skips items where
    score_str not in ("", None) but doesn't check for NaN/Inf after float conversion.
    """

    def _write_per_item_with_score(self, run_dir: pathlib.Path, scores: list) -> None:
        """Overwrite per_item.csv with explicit score values."""
        ids = [f"item-{i}" for i in range(len(scores))]
        rows = [
            {"item_id": iid, "score": str(s) if s is not None else "",
             "disposition": "correct" if s and s > 0 else "wrong",
             "finish_reason": "stop", "response_chars": 100, "empty_content": False}
            for iid, s in zip(ids, scores)
        ]
        buf = io.StringIO()
        w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
        (run_dir / "per_item.csv").write_text(buf.getvalue())

    def test_per_item_missing_score_fails_for_current_run(self):
        """A current-lifecycle run where any item has empty score string must fail.

        The empty score means the item was not scored — this is a data integrity gap.
        validate() must not silently skip the item and compute an aggregate from fewer items.
        """
        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo, n_items=5)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            # Item 2 has missing score (empty string)
            scores = [1.0, 1.0, None, 1.0, 1.0]  # None → empty string
            self._write_per_item_with_score(run_dir, scores)

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)
            # Current fixture aggregate claims 100% score but item 2 has no score.
            # The reconciliation computed from 4 items (not 5) will give 1.0, matching
            # the aggregate — but item 2's score is missing (integrity gap).
            # This test targets: does validate() detect the missing score?
            missing_score_errors = [
                e for e in result.errors
                if "score" in e.lower() and ("missing" in e.lower() or "empty" in e.lower()
                                              or "nonfinite" in e.lower() or "nan" in e.lower())
            ]
            # The gap: current implementation silently skips empty scores and may pass.
            # We want it to fail with a clear error about missing per-item score.
            self.assertFalse(
                result.passed,
                f"validate() must fail when a current-run per-item score is missing/empty. "
                f"errors: {result.errors}"
            )

    def test_per_item_nan_string_score_fails(self):
        """A per-item score of 'nan' string must be caught as non-finite."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo, n_items=5)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            # Write "nan" as a score for item 1
            ids = [f"item-{i}" for i in range(5)]
            rows = [
                {"item_id": iid,
                 "score": "nan" if i == 1 else "1.0",
                 "disposition": "correct",
                 "finish_reason": "stop",
                 "response_chars": 100,
                 "empty_content": False}
                for i, iid in enumerate(ids)
            ]
            buf = io.StringIO()
            w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
            (run_dir / "per_item.csv").write_text(buf.getvalue())

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)
            self.assertFalse(
                result.passed,
                f"validate() must fail when a per-item score is 'nan' (non-finite). "
                f"errors: {result.errors}"
            )



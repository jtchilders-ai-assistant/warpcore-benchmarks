            tampered_content = "suite_id: tampered-suite\n"
            tampered_file = pathlib.Path(tmp) / "tampered.yaml"
            tampered_file.write_text(tampered_content)

            # The manifest's suite hash was computed against the real content.
            # If we symlink the suite to tampered content, hash must fail.
            suite_yaml.unlink()
            suite_yaml.symlink_to(tampered_file)

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)

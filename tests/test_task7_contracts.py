class TestG4GitleaksSecretScan(unittest.TestCase):
    """Secret scan must use the real gitleaks binary when installed, not just
    regex over command.txt and run.log.

    A real credential placed in a raw/ artifact (not in command.txt or run.log)
    must be detected when gitleaks is available.
    """

    @classmethod
    def _gitleaks_available(cls) -> bool:
        return validate_campaign._resolve_gitleaks_bin() is not None

    def test_secret_in_raw_artifact_detected_by_gitleaks(self):
        """A real API key in raw/ must be detected.

        Current behavior: _secret_scan only scans command.txt and run.log.
        A secret in raw/evidence.txt is invisible to current implementation.
        """
        if not self._gitleaks_available():
            self.skipTest("gitleaks not installed; skip gitleaks-specific test")

        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            # Place a fake (non-real) secret that matches gitleaks patterns in raw/
            # Using a plausible-looking fake key that won't scan as real credential
            # but does match gitleaks's OpenAI/GitHub patterns
            # We use a format-compliant but obviously fake key
            fake_key = "ghp_" + "A" * 36  # GitHub Personal Access Token format (fake)
            (run_dir / "raw" / "debug_output.txt").write_text(
                f"# Debug output\ntoken={fake_key}\n"
            )

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)
            self.assertFalse(
                result.passed,
                f"Secret in raw/ artifact must be detected when gitleaks is installed. "
                f"errors: {result.errors}"
            )
            secret_errors = [e for e in result.errors
                             if "secret" in e.lower() or "credential" in e.lower()
                             or "gitleaks" in e.lower() or "token" in e.lower()
                             or "key" in e.lower()]
            self.assertTrue(
                len(secret_errors) > 0,
                f"Must have a secret-scan error; got: {result.errors}"
            )

    def test_clean_raw_artifacts_pass_gitleaks(self):
        """A run with no secrets in any artifact must pass gitleaks scan."""
        if not self._gitleaks_available():
            self.skipTest("gitleaks not installed; skip gitleaks-specific test")

        with tempfile.TemporaryDirectory() as tmp:
            repo = pathlib.Path(tmp) / "repo"
            run_dir = _build_quality_run(repo)
            suite_yaml = _make_suite_yaml(repo)
            adapter_yaml = _make_adapter_yaml(repo, "test-model")

            result = validate_campaign.validate(run_dir, suite_yaml, adapter_yaml)
            secret_errors = [e for e in result.errors
                             if "secret" in e.lower() or "credential" in e.lower()
                             or "gitleaks" in e.lower()]
            self.assertEqual(
                secret_errors, [],
                f"Clean run must not have secret-scan errors; got: {secret_errors}"
            )



